import { createFileRoute } from "@tanstack/react-router";
import { Save, Sparkles, Trash2 } from "lucide-react";
import { useState, type FormEvent } from "react";
import { toast } from "sonner";

import { Field, inputClass } from "@/components/field";
import { PageHeader } from "@/components/page-header";
import { Button } from "@/components/ui/button";
import { activityStore, chatStore } from "@/lib/activity";
import { settingsStore } from "@/lib/ai";
import { LIMITS } from "@/lib/ai-schema";
import { useHydrated } from "@/lib/storage";

export const Route = createFileRoute("/settings")({
  head: () => ({
    meta: [
      { title: "Settings · AI Workplace Productivity Assistant" },
      {
        name: "description",
        content: "Set your name and manage the data saved in this browser.",
      },
      { property: "og:title", content: "Settings" },
      {
        property: "og:description",
        content: "Set your name and manage the data saved in this browser.",
      },
    ],
  }),
  component: SettingsPage,
});

function SettingsPage() {
  const hydrated = useHydrated();
  return (
    <>
      <PageHeader
        title="Settings"
        description="Personalise your workspace and manage saved data."
      />
      {hydrated ? <SettingsForm /> : null}
    </>
  );
}

function SettingsForm() {
  const [name, setName] = useState(() => settingsStore.get().name);

  const save = (e: FormEvent) => {
    e.preventDefault();
    settingsStore.set({ name: name.trim() });
    toast.success("Settings saved");
  };

  return (
    <div className="grid gap-6 lg:grid-cols-3">
      <div className="space-y-6 lg:col-span-2">
        <form onSubmit={save} className="surface space-y-5 p-5 sm:p-6">
          <h2 className="text-lg font-semibold">Your profile</h2>
          <Field
            label="Your name"
            htmlFor="name"
            hint="Used in the welcome message and email sign-offs."
          >
            <input
              id="name"
              maxLength={LIMITS.sender}
              className={inputClass}
              placeholder="e.g. Toni Abrahams"
              value={name}
              onChange={(e) => setName(e.target.value)}
            />
          </Field>
          <Button type="submit">
            <Save /> Save settings
          </Button>
        </form>

        <section className="surface p-5 sm:p-6">
          <div className="flex flex-wrap items-center justify-between gap-3">
            <h2 className="text-lg font-semibold">AI</h2>
            <span className="inline-flex items-center gap-1.5 rounded-full bg-ink px-3 py-1 text-xs font-semibold text-brand">
              <Sparkles className="size-3.5" /> Built in
            </span>
          </div>
          <p className="mt-2 text-sm text-muted-foreground">
            AI is built into this app, so there is nothing to set up. Every email, research brief
            and chat answer is generated by AI when you ask for it.
          </p>
        </section>
      </div>

      <div className="space-y-6">
        <section className="surface p-5 sm:p-6">
          <h2 className="text-lg font-semibold">Saved data</h2>
          <p className="mt-1 text-sm text-muted-foreground">
            Recent activity and chat history are saved in this browser only.
          </p>
          <div className="mt-4 flex flex-col gap-2">
            <Button
              variant="outline"
              onClick={() => {
                activityStore.set([]);
                toast.success("Recent activity cleared");
              }}
            >
              <Trash2 /> Clear recent activity
            </Button>
            <Button
              variant="outline"
              onClick={() => {
                chatStore.set([]);
                toast.success("Chat history cleared");
              }}
            >
              <Trash2 /> Clear chat history
            </Button>
          </div>
        </section>

        <section className="rounded-2xl bg-ink p-5 text-background sm:p-6">
          <h2 className="text-lg font-semibold text-brand">Responsible AI</h2>
          <p className="mt-2 text-sm leading-relaxed text-background/80">
            AI-generated content may contain errors, omissions or outdated information. Review,
            fact-check and edit everything before using it professionally, and avoid entering
            confidential or personal information.
          </p>
        </section>
      </div>
    </div>
  );
}
